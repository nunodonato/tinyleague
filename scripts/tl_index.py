#!/usr/bin/env python
"""Compute the TL-Index — a composite benchmark index for the Tiny League roster.

Reads data/scores.json (generated by merge.py) and emits, per model, a 0-100
composite over nine benchmark columns chosen for coverage + domain balance.

Method (mirrored into data/tl_index.json so every number is auditable):
  1. Comparability filter. Some columns are reported in several flavours on the
     model cards (HLE with/without tools, τ³-bench Banking vs whole bench,
     BrowseComp single- vs multi-agent). Only one flavour per column is
     comparable, so the alternatives are dropped from the index (they stay in
     scores.json and on the site). See MODE_EXCLUDE / MODE_REQUIRE below.
  2. Normalize each benchmark to 0-100 with FIXED anchors (floor, ceiling):
     norm = clip((x - floor) / (ceiling - floor) * 100, 0, 100).
     Anchors are pinned literals, so the index does not drift when the roster
     changes; re-calibrate only on a major version bump.
  3. Strict completeness. A model is scored only if it reports EVERY benchmark
     in the index; there is no renormalization over the reported subset. Models
     missing a column get no TL-Index (they are listed with what's missing), so
     a sparse model can never be ranked above a complete one.
  4. Weighted mean of the nine normalized values, weights summing to 100.

Usage:
    .venv/bin/python scripts/tl_index.py            # ranked table
    .venv/bin/python scripts/tl_index.py --equal    # equal weights
    .venv/bin/python scripts/tl_index.py --json     # write data/tl_index.json
    .venv/bin/python scripts/tl_index.py --all      # list unscored models too
"""
